const isObj = (v) => v !== null && typeof v === "object" && !Array.isArray(v);
const isInt = (v) => typeof v === "number" && Number.isInteger(v);
const pyRepr = (v) => (v === null || v === undefined ? "None" : typeof v === "string" ? `'${v}'` : String(v));

// Python's json.loads accepts NaN / Infinity (they occur in stats.json); JSON.parse does not.
export function parseJSON(text) {
  try {
    return JSON.parse(text);
  } catch (e) {
    const fixed = text.replace(/-?\bInfinity\b|\bNaN\b/g, "null");
    if (fixed !== text) return JSON.parse(fixed);
    throw e;
  }
}

function res(id, level, passed, detail, extra = {}) {
  return { id, level, passed, detail, source: id.startsWith("G") ? SOURCES[id] ?? null : null,
           blocked_by: null, data: {}, ...extra };
}
const skip = (id, level, why, blockedBy) => res(id, level, null, `skipped: ${why}`, { blocked_by: blockedBy });

export class Ctx {
  constructor(view) {
    this.view = view;
    this.files = view.files;
    this.oversize = new Set();
    [this.info, this.infoErr] = this._json("meta/info.json");
    if (this.info !== null && !isObj(this.info)) [this.info, this.infoErr] = [null, "info.json is not a JSON object"];
    [this.modality, this.modalityErr] = this._json("meta/modality.json");
    if (this.modality !== null && !isObj(this.modality)) [this.modality, this.modalityErr] = [null, "modality.json is not a JSON object"];
    [this.stats, this.statsErr] = this._json("meta/stats.json");
    [this.episodes, this.episodesErr] = this._jsonl("meta/episodes.jsonl");
    [this.tasks, this.tasksErr] = this._jsonl("meta/tasks.jsonl");
  }
  _overCap(rel) {
    if (this.files[rel] > MAX_META_BYTES) {
      this.oversize.add(rel);
      return `SKIPPED(size): ${rel} is ${this.files[rel].toLocaleString("en-US")} B > ${MAX_META_BYTES.toLocaleString("en-US")} B cap`;
    }
    return null;
  }
  _json(rel) {
    if (!(rel in this.files)) return [null, `${rel} not found`];
    const cap = this._overCap(rel);
    if (cap) return [null, cap];
    const text = this.view.readText(rel);
    if (text === null || text === undefined) return [null, `${rel} not readable (size cap or fetch error)`];
    try {
      return [parseJSON(text), null];
    } catch (e) {
      return [null, `${rel} does not parse: ${e.message}`];
    }
  }
  _jsonl(rel) {
    if (!(rel in this.files)) return [null, `${rel} not found`];
    const cap = this._overCap(rel);
    if (cap) return [null, cap];
    const text = this.view.readText(rel);
    if (text === null || text === undefined) return [null, `${rel} not readable (size cap or fetch error)`];
    const rows = [];
    // Mirror the loader: `for line in f: json.loads(line)`; a blank line mid-file raises.
    const lines = text === "" ? [] : text.split(/(?<=\n)/);
    for (let n = 0; n < lines.length; n++) {
      try {
        rows.push(parseJSON(lines[n]));
      } catch (e) {
        return [null, `${rel} line ${n + 1} does not parse: ${e.message}`];
      }
    }
    return [rows, null];
  }
  get features() {
    const f = (this.info || {}).features;
    return isObj(f) ? f : {};
  }
  get videoFeatures() {
    return Object.entries(this.features).filter(([, v]) => isObj(v) && v.dtype === "video").map(([k]) => k);
  }
  isV3Layout() {
    const info = this.info || {};
    const pats = `${info.data_path ?? ""} ${info.video_path ?? ""}`;
    return String(info.codebase_version ?? "").startsWith("v3") || pats.includes("file_index") ||
      pats.includes("chunk_index") || "meta/tasks.parquet" in this.files ||
      Object.keys(this.files).some((p) => p.startsWith("meta/episodes/"));
  }
}

// ---------------------------------------------------------------- str.format helpers

// string.Formatter().parse: field names of a pattern, first segment only ("a.b" -> "a").
function placeholders(pattern) {
  const names = new Set();
  const re = /\{\{|\}\}|\{([^{}]*)\}/g;
  let m;
  while ((m = re.exec(pattern))) {
    if (m[1] === undefined) continue;
    const field = m[1].split(/[!:]/)[0];
    names.add(field.split(".")[0].split("[")[0]);
  }
  return names;
}

// Minimal Python str.format for the integer specs LeRobot uses ("{episode_index:06d}").
export function pyFormat(pattern, values) {
  return pattern.replace(/\{\{|\}\}|\{([^{}]*)\}/g, (all, body) => {
    if (body === undefined) return all[0];
    const [field, spec = ""] = body.split(":");
    if (!(field in values)) throw new Error(`KeyError: '${field}'`);
    const v = values[field];
    const m = spec.match(/^(0?)(\d*)d?$/);
    if (!m) return String(v);
    const width = Number(m[2] || 0);
    return String(v).padStart(width, m[1] === "0" ? "0" : " ");
  });
}

function fmtOk(pattern, allowed, sample) {
  if (typeof pattern !== "string") return [false, `pattern is ${pattern === null ? "NoneType" : typeof pattern}, not a string`];
  const ph = placeholders(pattern);
  const extra = [...ph].filter((p) => !allowed.has(p)).sort();
  if (extra.length) {
    return [false, `placeholders [${extra.map((e) => `'${e}'`).join(", ")}] not supplied by the loader ` +
      `(has [${[...allowed].sort().map((e) => `'${e}'`).join(", ")}]); would KeyError`];
  }
  try {
    pyFormat(pattern, sample);
  } catch (e) {
    return [false, `.format() raises ${e.message}`];
  }
  return [true, `placeholders [${[...ph].sort().map((e) => `'${e}'`).join(", ")}]`];
}


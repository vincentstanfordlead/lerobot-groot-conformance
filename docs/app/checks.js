export function runLChecks(x) {
  const out = [];
  const files = Object.keys(x.files);
  const L = (id, level, passed, detail, extra = {}) => out.push(res(id, level, passed, detail, extra));
  const hasMeta = files.some((p) => p.startsWith("meta/"));
  L("L1", "WARN", hasMeta && x.info !== null,
    x.info !== null ? "meta/info.json present and parses" : hasMeta ? x.infoErr : "no meta/ directory");
  if (x.info === null) return out;
  const info = x.info;
  const ver = info.codebase_version ?? null;
  L("L2", "INFO", ver !== null, `codebase_version=${pyRepr(ver)}`, { data: { codebase_version: ver } });
  const hasParquet = files.some((p) => p.startsWith("data/") && p.endsWith(".parquet"));
  L("L3", "INFO", hasParquet, hasParquet ? "data/ contains parquet" : "no parquet under data/");
  const hasVideos = files.some((p) => p.startsWith("videos/"));
  L("L4", "INFO", hasVideos, hasVideos ? "videos/ present" : "no videos/ (state-only dataset, not a defect)");
  const epLayout = "meta/episodes.jsonl" in x.files ? "jsonl"
    : files.some((p) => p.startsWith("meta/episodes/") && p.endsWith(".parquet")) ? "parquet" : null;
  L("L5", "WARN", epLayout !== null, `episode metadata layout: ${epLayout ?? "None"}`, { data: { layout: epLayout } });
  const taskLayout = "meta/tasks.jsonl" in x.files ? "jsonl" : "meta/tasks.parquet" in x.files ? "parquet" : null;
  L("L6", "WARN", taskLayout !== null, `task metadata layout: ${taskLayout ?? "None"}`, { data: { layout: taskLayout } });
  const statsLayout = "meta/stats.json" in x.files ? "stats.json"
    : "meta/episodes_stats.jsonl" in x.files ? "episodes_stats.jsonl" : null;
  L("L7", "WARN", statsLayout !== null, `stats layout: ${statsLayout ?? "None"}`, { data: { layout: statsLayout } });
  const feats = x.features;
  const dim = (k) => {
    const s = isObj(feats[k]) ? feats[k].shape : null;
    return Array.isArray(s) && s.length ? s[0] : null;
  };
  L("L8", "WARN", Object.keys(feats).length > 0,
    `state dim=${pyRepr(dim("observation.state"))}, action dim=${pyRepr(dim("action"))}, ` +
    `cameras=${x.videoFeatures.length}, fps=${pyRepr(info.fps ?? null)}`,
    { data: { state_dim: dim("observation.state"), action_dim: dim("action"), n_cameras: x.videoFeatures.length, fps: info.fps ?? null } });
  const named = {};
  for (const k of ["observation.state", "action"]) {
    const n = isObj(feats[k]) ? feats[k].names : null;
    named[k] = Boolean(n && (Array.isArray(n) ? n.length : isObj(n) ? Object.keys(n).length : true));
  }
  L("L9", "INFO", Object.values(named).every(Boolean), `names present: ${JSON.stringify(named)}`, { data: named });
  if (!x.videoFeatures.length) L("L10", "INFO", true, "no camera features");
  else if (!hasVideos) L("L10", "INFO", null, "videos/ absent; cannot verify camera dirs");
  else {
    const v3 = x.isV3Layout();
    const missing = x.videoFeatures.filter((k) => !files.some((p) => `/${p}`.includes(`/${k}/`) && p.startsWith("videos/")));
    if (missing.length && x.view.listingComplete === false) {
      L("L10", "INFO", null, `layout=${v3 ? "v3.0" : "v2.x"}; listing capped, not seen: ${JSON.stringify(missing)}`);
    } else {
      L("L10", "INFO", !missing.length, `layout=${v3 ? "v3.0" : "v2.x"}; missing camera dirs: ${JSON.stringify(missing)}`);
    }
  }
  const total = info.total_episodes;
  if (x.episodes === null) L("L11", "WARN", null, `episodes.jsonl unavailable (${x.episodesErr}); episode count not compared`);
  else if (!isInt(total)) L("L11", "WARN", null, "info.json:total_episodes absent; nothing to compare");
  else L("L11", "WARN", x.episodes.length === total, `episodes.jsonl lines=${x.episodes.length}, info.json:total_episodes=${total}`,
    { data: { episodes_lines: x.episodes.length, total_episodes: total } });
  const fps = info.fps;
  const fpsOk = typeof fps === "number" && fps > 0;
  L("L12", "WARN", fpsOk, fpsOk ? `fps=${fps}` : `fps=${pyRepr(fps ?? null)}: the loader silently assumes 30`,
    { source: FPS_SOURCE, data: { fps: fps ?? null } });
  return out;
}

